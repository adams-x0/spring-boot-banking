-- The SQL below is a complete starting schema for PostgreSQL. Each block builds on the previous one.

-- 1. bank_users stores the people who use the application

create table bank_users (
                            user_id bigint generated always as identity primary key,
                            username varchar(50) not null unique,
                            password_hash varchar(255) not null,
                            first_name varchar(100) not null,
                            last_name varchar(100) not null,
                            email varchar(254) not null,
                            role varchar(10) not null default 'CUSTOMER',
                            created_at timestamptz not null default current_timestamp,

                            check (role in ('CUSTOMER', 'EMPLOYEE')),
                            check (length(trim(username)) > 0),
                            check (length(trim(password_hash)) > 0),
                            check (length(trim(first_name)) > 0),
                            check (length(trim(last_name)) > 0),
                            check (length(trim(email)) > 0)
);

-- Column	Explanation
-- user_id	Automatically generated ID. The primary key uniquely identifies each person.
-- username	Unique login name. This definition treats uppercase and lowercase as distinct.
-- password_hash	Stores a password hash generated by Java.
-- first_name, last_name, email	Personal information employees can view.
-- role	Determines which console actions the user can access. Registration defaults to CUSTOMER.
-- created_at	Records when the user registered.


-- Employees have rows in this table with role = 'EMPLOYEE'. Employee creation should happen through a trusted setup process. Customer registration should always assign CUSTOMER.


-- 2. accounts stores applications and account balances

-- I’m using the same row for an application and its eventual approved account. Approval changes its status while preserving its ID.

create table accounts (
                          account_id bigint generated always as identity primary key,
                          balance numeric(15, 2) not null default 0.00,
                          status varchar(10) not null default 'PENDING',
                          applied_at timestamptz not null default current_timestamp,
                          reviewed_by bigint references bank_users(user_id),
                          reviewed_at timestamptz,

                          check (balance >= 0 and balance <> 'NaN'::numeric),
    check (status in ('PENDING', 'APPROVED', 'DENIED')),
    -- If status = 'APPROVED', any balance is allowed.
    -- If status is PENDING or DENIED, the balance must be 0.
    check (status = 'APPROVED' or balance = 0),
    check (
        (status = 'PENDING'
            and reviewed_by is null
            and reviewed_at is null)
        or
        (status in ('APPROVED', 'DENIED')
            and reviewed_by is not null
            and reviewed_at is not null)
    ),
    check (reviewed_at >= applied_at)
);


-- Column	Explanation
-- account_id	Unique identifier for the application and account.
-- balance	Money currently in the account. NUMERIC(15, 2) stores exact decimal values with two decimal places. Use Java BigDecimal with it.
-- status	PENDING while waiting for review, then APPROVED or DENIED.
-- applied_at	When the application was submitted.
-- reviewed_by	The user ID of the employee who made the decision.
-- reviewed_at	When the employee reviewed it.


-- The constraints prevent negative balances and require pending or denied accounts to have a zero balance. They also require review details once a decision is recorded.

-- reviewed_by is a foreign key. PostgreSQL checks that this user exists.################The service must also verify that the reviewer is an employee.####################

-- 3. account_owners supports individual and joint accounts

-- Each row connects one user to one account.

create table account_owners (
                                account_id bigint not null references accounts(account_id),
                                user_id bigint not null references bank_users(user_id),

-- This means the combination of both columns must be unique.

-- Valid:

-- Plain Text
-- account_id | user_id
-- -----------+--------
-- 101 | 1
-- 101 | 2
-- 102 | 1

--  Invalid:

-- Plain Text
-- account_id | user_id
-- -----------+--------
-- 101 | 1
-- 101 | 1
                                primary key (account_id, user_id)

);

-- primary key is great for queries that start with account_id, such as:

-- SQL
-- WHERE account_id = 50
-- But it's not optimal for:

-- SQL
-- WHERE user_id = 101

-- because user_id is the second column in the primary-key index.

-- The index makes finding all rows for a particular user_id much faster.

create index account_owners_user_id_idx
    on account_owners(user_id);

-- Column	Explanation
-- account_id	Identifies an account.
-- user_id	Identifies one of its owners.


-- The two columns together form a composite primary key, preventing duplicate ownership entries.

-- For example, these rows describe one joint account and one individual account.
-- account_id	user_id	Meaning
-- 101	1	Maya owns account 101.
-- 101	2	Jordan also owns account 101.
-- 102	1	Maya owns account 102.


-- Account 101 has one shared balance in accounts. Both users access that balance through their ownership records.

-- This is a many-to-many relationship because one user can own several accounts, and one account can have several owners. The index helps find all accounts belonging to a particular user.

-- What problem does it solve?

-- Without this table:

-- One account → one user

-- But banks often allow:

-- One user → many accounts
-- One account → many users (joint checking/savings)

-- That's a many-to-many relationship, and account_owners handles it.

-- The application must create the account and its ownership rows in one database transaction. It must ensure every application has at least one owner and obtain each joint applicant’s agreement before submitting it.


-- 4. bank_transactions records money movements

-- Transaction history is a design addition that makes deposits, withdrawals, and transfers traceable during your demonstration.

create table bank_transactions (
                                   transaction_id bigint generated always as identity primary key,
                                   transaction_type varchar(10) not null,
                                   amount numeric(15, 2) not null,
                                   source_account_id bigint references accounts(account_id),
                                   destination_account_id bigint references accounts(account_id),
                                   performed_by bigint not null references bank_users(user_id),
                                   created_at timestamptz not null default current_timestamp,

                                   check (amount > 0 and amount <> 'NaN'::numeric),
    check (
        (
            transaction_type = 'DEPOSIT'
                and source_account_id is null
                and destination_account_id is not null
        )
        or
        (
            transaction_type = 'WITHDRAWAL'
                and source_account_id is not null
                and destination_account_id is null
        )
        or
        (
            transaction_type = 'TRANSFER'
                and source_account_id is not null
                and destination_account_id is not null
                and source_account_id <> destination_account_id
        )
    )

);

create index bank_transactions_source_idx
    on bank_transactions(source_account_id);

create index bank_transactions_destination_idx
    on bank_transactions(destination_account_id);

-- Column	Explanation
-- transaction_id	Unique identifier for the operation.
-- transaction_type	DEPOSIT, WITHDRAWAL, or TRANSFER.
-- amount	Positive amount moved.
-- source_account_id	Account money leaves. Empty for deposits.
-- destination_account_id	Account money enters. Empty for withdrawals.
-- performed_by	The logged-in user who initiated the operation.
-- created_at	When the operation occurred.
